# 延遲初始化 OpenAI Client
client = None

def get_openai_client():
    """獲取 OpenAI 客戶端，延遲初始化"""
    global client
    if client is None:
        api_key = os.getenv("OPENAI_API_KEY")
        if not api_key:
            raise ValueError("OPENAI_API_KEY 環境變數未設定")
        client = OpenAI(api_key=api_key)
    return client

